// Outlines A-Z and 0-9 from Inter 650 (opsz 32) into scripts/glyphs.js, so a product icon can
// carry a letter without a font. Rerun only if the lettering changes:
//   bun scripts/glyphs.mjs path/to/Inter[opsz,wght].ttf
import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const font = fontkit.openSync(process.argv[2]).getVariation({ wght: 650, opsz: 32 });
const k = 100 / font.capHeight, r = (n) => +n.toFixed(1);
const letters = { moveTo: "M", lineTo: "L", quadraticCurveTo: "Q", bezierCurveTo: "C", closePath: "Z" };
const out = {};
for (const ch of "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789") {
  const g = font.layout(ch).glyphs[0], { minX, maxX } = g.bbox;
  let d = "";
  for (const c of g.path.commands) {
    const pts = [];
    for (let j = 0; j < c.args.length; j += 2) pts.push(r((c.args[j] - minX) * k), r(-c.args[j + 1] * k));
    d += letters[c.command] + pts.join(" ");
  }
  out[ch] = [r((maxX - minX) * k), d.replace(/ -/g, "-")];
}
const file = join(dirname(fileURLToPath(import.meta.url)), "glyphs.js");
writeFileSync(file, `// Generated by scripts/glyphs.mjs from Inter 650 (SIL Open Font License 1.1); don't edit by hand.
// Each letter is [width, path]: cap height 100, baseline at y = 0, left edge at x = 0.
globalThis.zxGlyphs = ${JSON.stringify(out).replace(/\],"/g, '],\n"').replace(/^\{/, "{\n").replace(/\}$/, "\n}")};
`);
console.log(`wrote ${file}`);
