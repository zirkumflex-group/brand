// Outlines "Zirkumflex" and "Flexspeak" in Inter 650 (opsz 32) and writes logo/lockup.svg and
// logo/lockup-flexspeak.svg, so the lockups look right without Inter installed.
// Run it only when the mark, the badge or the lettering changes:
//   bun install                     (fontkit is a dev dependency)
//   bun scripts/lockup.mjs path/to/Inter[opsz,wght].ttf
// Inter's variable font: https://github.com/google/fonts/tree/main/ofl/inter
import * as fontkit from "fontkit";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const fontPath = process.argv[2];
if (!fontPath) throw new Error("usage: bun scripts/lockup.mjs path/to/Inter[opsz,wght].ttf");
const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const ink = JSON.parse(readFileSync(join(repo, "tokens.json"), "utf8")).color.light.text;

// Each lockup in currentColor (for inlining), white (dark backgrounds) and ink (light backgrounds).
function write(name, svg) {
  writeFileSync(`${repo}/logo/${name}.svg`, svg);
  for (const [suffix, colour, note] of [["-white", "#ffffff", "white"], ["-ink", ink, "the light palette's text colour"]]) {
    writeFileSync(`${repo}/logo/${name}${suffix}.svg`, svg.replace(", in currentColor.", `, in ${note}.`).replace("is in currentColor", `is in ${note}`).replaceAll("currentColor", colour));
  }
  console.log(name);
}
const base = fontkit.openSync(fontPath);
const font = base.getVariation({ wght: 650, opsz: 32 });
const F = 100, upm = font.unitsPerEm, k = F / upm, track = -0.02 * F;
const r = (n) => +n.toFixed(1);
function text(str, x0, baseline) {
  const run = font.layout(str);
  let x = x0, d = "";
  run.glyphs.forEach((g, i) => {
    const cmds = g.path.commands;
    for (const c of cmds) {
      const pts = [];
      for (let j = 0; j < c.args.length; j += 2) pts.push(r(x + c.args[j] * k), r(baseline - c.args[j + 1] * k));
      d += { moveTo: "M", lineTo: "L", quadraticCurveTo: "Q", bezierCurveTo: "C", closePath: "Z" }[c.command] + pts.join(" ");
    }
    x += run.positions[i].xAdvance * k + (i < run.glyphs.length - 1 ? track : 0);
  });
  return { d: d.replace(/ -/g, "-"), right: x };
}
const cap = font.capHeight * k;
// Zirkumflex: the mark sits on the baseline, its top a little above cap height.
{
  const mh = 0.8 * F, s = mh / 17.28, mw = 22 * s, gap = 0.22 * F, base = mh;
  const leg = (pts) => "M" + pts.map(([x, y]) => `${r((x - 1) * s)} ${r((y - 3.36) * s)}`).join(" L") + " Z";
  const back = leg([[9.88, 3.36], [14.94, 3.36], [23, 16.32], [17.95, 16.32]]);
  const front = leg([[1, 20.64], [6.54, 20.64], [14.94, 3.36], [9.39, 3.36]]);
  const t = text("Zirkumflex", mw + gap, base);
  const w = Math.ceil(t.right), h = Math.ceil(base);
  write("lockup", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">
  <!-- The mark and "Zirkumflex" outlined in Inter 650, in currentColor. Generated by scripts/lockup.mjs. -->
  <path d="${back}" fill="currentColor" fill-opacity="0.6"/>
  <path d="${front}" fill="currentColor"/>
  <path d="${t.d}" fill="currentColor"/>
</svg>
`);
}
// Flexspeak: the badge, centred on the cap height, then the name.
{
  const d = 1.4 * F, pad = (d - cap) / 2, baseline = pad + cap, gap = 0.32 * F;
  const badge = readFileSync(`${repo}/logo/flexspeak.svg`, "utf8")
    .replace(/<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*<!--[^>]*-->/g, "")
    .replace(/id="(\w+)"/g, 'id="fx-$1"').replace(/url\(#(\w+)\)/g, "url(#fx-$1)").trim();
  // The badge disc is r=464 of 1024, so scale the 1024 box until the disc is d across.
  const box = d * 1024 / 928, off = -(box - d) / 2;
  const t = text("Flexspeak", d + gap, baseline);
  const w = Math.ceil(t.right), h = Math.ceil(d);
  write("lockup-flexspeak", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">
  <!-- The Flexspeak badge and name outlined in Inter 650; the name is in currentColor. Generated by scripts/lockup.mjs. -->
  <svg x="${r(off)}" y="${r(off)}" width="${r(box)}" height="${r(box)}" viewBox="0 0 1024 1024">
  ${badge.replace(/\n  /g, "\n    ")}
  </svg>
  <path d="${t.d}" fill="currentColor"/>
</svg>
`);
}
