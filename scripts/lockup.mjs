// Outlines "Zirkumflex" and "Flexspeak" in Inter 650 (opsz 32) and writes logo/lockup*.svg and
// logo/lockup-flexspeak*.svg, so the lockups look right without Inter installed.
// Run it only when the mark, the badge or the lettering changes:
//   bun install                     (fontkit is a dev dependency)
//   bun scripts/lockup.mjs path/to/Inter[opsz,wght].ttf
// Inter's variable font: https://github.com/google/fonts/tree/main/ofl/inter
// For another product's lockup, use scripts/product.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { F, outliner, iconLockup, variants } from "./outline.mjs";

const fontPath = process.argv[2];
if (!fontPath) throw new Error("usage: bun scripts/lockup.mjs path/to/Inter[opsz,wght].ttf");
const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const ink = JSON.parse(readFileSync(join(repo, "tokens.json"), "utf8")).color.light.text;
const o = outliner(fontPath);
const r = (n) => +n.toFixed(1);

// Each lockup in currentColor (for inlining), white (dark backgrounds) and ink (light backgrounds).
function write(name, svg) {
  for (const [suffix, body] of Object.entries(variants(svg, ink))) writeFileSync(join(repo, "logo", `${name}${suffix}.svg`), body);
  console.log(name);
}

// Zirkumflex: the mark sits on the baseline, its top a little above cap height.
{
  const mh = 0.8 * F, s = mh / 17.28, mw = 22 * s, gap = 0.22 * F, base = mh;
  const leg = (pts) => "M" + pts.map(([x, y]) => `${r((x - 1) * s)} ${r((y - 3.36) * s)}`).join(" L") + " Z";
  const back = leg([[9.88, 3.36], [14.94, 3.36], [23, 16.32], [17.95, 16.32]]);
  const front = leg([[1, 20.64], [6.54, 20.64], [14.94, 3.36], [9.39, 3.36]]);
  const t = o.text("Zirkumflex", mw + gap, base);
  const w = Math.ceil(t.right), h = Math.ceil(base);
  write("lockup", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">
  <!-- The mark and "Zirkumflex" outlined in Inter 650, in currentColor. Generated by scripts/lockup.mjs. -->
  <path d="${back}" fill="currentColor" fill-opacity="0.6"/>
  <path d="${front}" fill="currentColor"/>
  <path d="${t.d}" fill="currentColor"/>
</svg>
`);
}

// Flexspeak: the badge, centred on the cap height, then the name.
write("lockup-flexspeak", iconLockup(o, readFileSync(join(repo, "logo", "flexspeak.svg"), "utf8"), "Flexspeak",
  "The Flexspeak badge and name outlined in Inter 650; the name is in currentColor. Generated by scripts/lockup.mjs."));
